# Update the FinancialDoc class in backend/db/models.py
class FinancialDoc(Base):
    __tablename__ = "financial_docs"
 
    id = Column(Integer, primary_key=True, index=True)
    content = Column(Text, nullable=False)
    embedding = Column(Vector(384))
    source = Column(String, nullable=True)  # e.g. "rbi_financial_literacy_guide.pdf"
 
 
class UserProfile(Base):
    __tablename__ = "user_profiles"
 
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String, unique=True, index=True, default="demo_user")
    age = Column(Integer, nullable=True)
    occupation = Column(String, nullable=True)
    annual_income = Column(Float, nullable=True)
    land_acres = Column(Float, nullable=True)
    has_disability = Column(Boolean, default=False)
    has_daughter_under_10 = Column(Boolean, default=False)
    is_woman = Column(Boolean, default=False)
    is_sc_st = Column(Boolean, default=False)
 
 
class FinTwinRecord(Base):
    __tablename__ = "fintwin_records"
 
    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(String, index=True, default="demo_user")
    monthly_income = Column(Float, default=0)
    expenses = Column(JSON, default=dict)  # default=dict, not default={}
    savings = Column(Float, default=0)
    debts = Column(Float, default=0)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
 
 
class SHGGroup(Base):
    __tablename__ = "shg_groups"
    id = Column(Integer, primary_key=True)
    group_id = Column(String, unique=True, index=True)
    group_name = Column(String)
    ngo_name = Column(String, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)
 
class GroupMember(Base):
    __tablename__ = "group_members"
    id = Column(Integer, primary_key=True)
    group_id = Column(String, index=True)
    phone_number = Column(String, index=True)
    display_name = Column(String)
    first_contact_at = Column(DateTime, nullable=True)
    influence_score = Column(Float, default=0.0)
    is_top_connector = Column(Boolean, default=False)
 
class Interaction(Base):
    __tablename__ = "interactions"
    id = Column(Integer, primary_key=True)
    group_id = Column(String, index=True, nullable=True)
    phone_number = Column(String, index=True)
    message = Column(Text)
    response = Column(Text)
    channel = Column(String, default="whatsapp_text")
    topic = Column(String, nullable=True)
    timestamp = Column(DateTime, default=datetime.utcnow)
 
class SeedingEvent(Base):
    __tablename__ = "seeding_events"
    id = Column(Integer, primary_key=True)
    group_id = Column(String, index=True)
    seeded_to = Column(String)
    content_summary = Column(String)
    seeded_at = Column(DateTime, default=datetime.utcnow)
    members_reached_72h = Column(Integer, default=0)
    total_group_size = Column(Integer, default=0)
 
 
# Added for Lakshmi web-chat — multi-session history (ChatGPT-style sidebar)
class ChatSession(Base):
    __tablename__ = "chat_sessions"
 
    id = Column(String, primary_key=True)  # uuid string, generated by backend
    title = Column(String, default="New Chat")
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)
 
 
class ChatMessage(Base):
    __tablename__ = "chat_messages"
 
    id = Column(Integer, primary_key=True, index=True)
    session_id = Column(String, index=True)
    role = Column(String)          # "user" or "bot"
    text = Column(Text)
    timestamp = Column(DateTime, default=datetime.utcnow)
 
 
def init_db():
    from sqlalchemy import text
    with engine.connect() as conn:
        conn.execute(text("CREATE EXTENSION IF NOT EXISTS vector"))
        conn.commit()
    Base.metadata.create_all(bind=engine)
 